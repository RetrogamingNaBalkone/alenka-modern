"""Rebuild the app icon from the first A in the original intro (stdlib only)."""
import argparse
import struct
from pathlib import Path

from inspect_resources import png

ROOT = Path(__file__).resolve().parents[1]
BACKGROUND = (40, 42, 46)
SIZES = (16, 20, 24, 32, 48, 64, 128, 256)


def source_letter():
    lib = (ROOT / 'original/ALENKA/ALLE.LIB').read_bytes()
    fld = (ROOT / 'original/ALENKA/ALLE.FLD').read_bytes()
    width = struct.unpack_from('<H', lib, 6)[0] + 1
    lines = struct.unpack_from('<H', lib, 4)[0] + 1
    plane = width * lines
    fw = struct.unpack_from('<H', fld, 8)[0]
    palette = [tuple((0, 85, 170, 255)[c] for c in struct.unpack_from('<3H', lib, 18+i*6)) for i in range(17)]
    pixels = []
    # Crop only the first letter, including its original grey extrusion.
    for y in range(160, 255):
        row = []
        for x in range(64, 144):
            ptr = struct.unpack_from('<H', fld, 32 + 2*((y//8)*fw+x//8))[0] - 16000
            ax, ay = ptr % width * 8 + x % 8, ptr // width + y % 8
            color = sum(((lib[256+(3-p)*plane+ay*width+ax//8] >> (7-ax%8)) & 1) << p for p in range(4))
            row.append(palette[color] if color else BACKGROUND)
        pixels.append(row)
    return pixels


def image(size):
    letter = source_letter()
    # EGA pixels are taller than square pixels: restore the intro's 48/35 ratio.
    height = 208
    width = round(height * 80 / (95 * 48 / 35))
    left, top = (256-width)//2, (256-height)//2
    canvas = []
    for y in range(256):
        for x in range(256):
            canvas.append(letter[(y-top)*95//height][(x-left)*80//width]
                          if left <= x < left+width and top <= y < top+height else BACKGROUND)
    # Area sampling keeps the thin white outline visible at taskbar sizes.
    pixels = bytearray()
    for y in range(size):
        for x in range(size):
            total = [0, 0, 0]
            weight = 0
            for sy in range(y*256//size, ((y+1)*256+size-1)//size):
                wy = min((y+1)*256, (sy+1)*size)-max(y*256, sy*size)
                for sx in range(x*256//size, ((x+1)*256+size-1)//size):
                    wx = min((x+1)*256, (sx+1)*size)-max(x*256, sx*size)
                    w = wx*wy
                    weight += w
                    for c in range(3):
                        total[c] += canvas[sy*256+sx][c]*w
            pixels.extend(round(c/weight) for c in total)
    return pixels


def generate(destination):
    destination.mkdir(parents=True, exist_ok=True)
    png(destination / 'alenka.png', 256, 256, image(256))
    entries, payloads = [], []
    offset = 6 + 16*len(SIZES)
    for size in SIZES:
        rgb = image(size)
        bitmap = bytearray()
        for y in reversed(range(size)):
            for x in range(size):
                r, g, b = rgb[(y*size+x)*3:(y*size+x+1)*3]
                bitmap.extend((b, g, r, 255))
        mask = bytes(((size+31)//32)*4*size)
        dib = struct.pack('<IiiHHIIiiII', 40, size, size*2, 1, 32, 0, len(bitmap), 0, 0, 0, 0) + bitmap + mask
        entries.append(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(dib), offset))
        payloads.append(dib)
        offset += len(dib)
    (destination / 'alenka.ico').write_bytes(struct.pack('<HHH', 0, 1, len(SIZES)) + b''.join(entries+payloads))
    rgb = image(64)
    # Embed RGB pixels so the window icon needs no extra runtime files or codecs.
    rows = [','.join(str(v) for v in rgb[i:i+96]) for i in range(0, len(rgb), 96)]
    header = '// Generated by tools/generate_icon.py; do not edit.\n#pragma once\nnamespace alenka {\n'
    header += 'inline constexpr unsigned char app_icon_rgb[] = {\n' + ',\n'.join(rows) + '\n};\n}\n'
    (destination / 'app_icon.hpp').write_text(header, encoding='utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', nargs='?', type=Path, default=ROOT / 'resources')
    generate(parser.parse_args().destination)
